            seedBlogsIntoDatabase($pdo, $blogs);
        }

        // Fetch from DB for live dynamic additions
        $sql = "SELECT * FROM blogs WHERE 1=1";
        $params = [];

        if (!empty($category) && $category !== 'all') {
            $sql .= " AND category = ?";
            $params[] = $category;
        }

        if (!empty($search)) {
            $sql .= " AND (title LIKE ? OR excerpt LIKE ? OR content LIKE ? OR keywords LIKE ?)";
            $term = "%{$search}%";
            $params[] = $term;
            $params[] = $term;
            $params[] = $term;
            $params[] = $term;
        }

        $sql .= " ORDER BY published_date DESC, id DESC";
        $stmt = $pdo->prepare($sql);
        $stmt->execute($params);
        $dbBlogs = $stmt->fetchAll(PDO::FETCH_ASSOC);

        if (!empty($dbBlogs)) {
            return $dbBlogs;
        }
    } catch (\Throwable $e) {
        // Fallback to static array in memory
    }

    // Filter static blogs in memory
    $filtered = $blogs;

    if (!empty($category) && $category !== 'all') {
        $filtered = array_filter($filtered, function($b) use ($category) {
            return strcasecmp($b['category'], $category) === 0;
        });
    }

    if (!empty($search)) {
        $searchLower = strtolower($search);
        $filtered = array_filter($filtered, function($b) use ($searchLower) {
            return strpos(strtolower($b['title']), $searchLower) !== false
                || strpos(strtolower($b['excerpt']), $searchLower) !== false
                || strpos(strtolower($b['keywords']), $searchLower) !== false
                || strpos(strtolower($b['content']), $searchLower) !== false;
        });
    }

    // Sort by date DESC
    usort($filtered, function($a, $b) {
        return strcmp($b['published_date'], $a['published_date']);
    });

    return array_values($filtered);
}

/**
 * Returns single blog by slug
 */
function getBlogBySlug($slug) {
    $slug = trim($slug);
    if (empty($slug)) return null;

    try {
        $pdo = getDBConnection();
        ensureBlogsTableExists($pdo);
        $stmt = $pdo->prepare("SELECT * FROM blogs WHERE slug = ? LIMIT 1");
        $stmt->execute([$slug]);
        $blog = $stmt->fetch(PDO::FETCH_ASSOC);
        if ($blog) {
            // Increment view count
            @$pdo->prepare("UPDATE blogs SET views = views + 1 WHERE id = ?")->execute([$blog['id']]);
            return $blog;
        }
    } catch (\Throwable $e) {}

    // Fallback to static
    $static = getStaticDailyBlogs();
    foreach ($static as $b) {
        if ($b['slug'] === $slug) {
            return $b;
        }
    }

    return null;
}

/**
 * Seeds static blogs into database if table is empty
 */
function seedBlogsIntoDatabase(PDO $pdo, array $blogs) {
    try {
        $stmt = $pdo->prepare("INSERT INTO `blogs` 
            (`slug`, `title`, `category`, `excerpt`, `content`, `author`, `image`, `meta_title`, `meta_description`, `keywords`, `read_time`, `published_date`, `views`)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 0)
            ON DUPLICATE KEY UPDATE title = VALUES(title), content = VALUES(content)");

        foreach ($blogs as $b) {
            $stmt->execute([
                $b['slug'],
                $b['title'],
                $b['category'],
                $b['excerpt'],
                $b['content'],
                $b['author'] ?? 'Malik Mehboob',
                $b['image'] ?? 'assets/images/courses/numerology.jpg',
                $b['meta_title'] ?? $b['title'],
                $b['meta_description'] ?? $b['excerpt'],
                $b['keywords'] ?? '',
                $b['read_time'] ?? '5 min read',
                $b['published_date']
            ]);
        }
    } catch (\Throwable $e) {}
}

function ensureBlogsTableExists(PDO $pdo) {
    static $checked = false;
    if ($checked) return;
    try {
        $pdo->exec("CREATE TABLE IF NOT EXISTS `blogs` (
            `id` INT AUTO_INCREMENT PRIMARY KEY,
            `slug` VARCHAR(191) NOT NULL UNIQUE,
            `title` VARCHAR(255) NOT NULL,
            `category` VARCHAR(100) NOT NULL,
            `excerpt` TEXT NOT NULL,
            `content` LONGTEXT NOT NULL,
            `author` VARCHAR(100) DEFAULT 'Malik Mehboob',
            `image` VARCHAR(255) DEFAULT 'assets/images/courses/numerology.jpg',
            `meta_title` VARCHAR(255) DEFAULT NULL,
            `meta_description` TEXT DEFAULT NULL,
            `keywords` VARCHAR(255) DEFAULT NULL,
            `read_time` VARCHAR(50) DEFAULT '5 min read',
            `published_date` DATE NOT NULL,
            `views` INT DEFAULT 0,
            `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            INDEX (`category`),
            INDEX (`published_date`)
        ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;");
        $checked = true;
    } catch (\Throwable $e) {}
}

